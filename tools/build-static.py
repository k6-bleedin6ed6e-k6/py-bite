#!/usr/bin/env python3
"""Render the Flask course templates as a static Cloudflare Pages site."""
from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import sys
sys.path.insert(0, str(ROOT))

from app import create_app
from app.content import CHAPTERS, RESOURCES
from app.quizzes import get_quiz

DIST = ROOT / 'dist'


def write_page(client, route: str, relative: str) -> None:
    response = client.get(route)
    if response.status_code != 200:
        raise RuntimeError(f'Could not render {route}: HTTP {response.status_code}')
    target = DIST / relative / 'index.html'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(response.data)


def main() -> None:
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir()
    app = create_app()
    app.config['TESTING'] = True
    client = app.test_client()

    write_page(client, '/', '')
    redirects = []
    chapters = {}
    lesson_ids = []
    for chapter in CHAPTERS:
        chapter_id = chapter['id']
        write_page(client, f'/chapter/{chapter_id}', f'chapter/{chapter_id}')
        write_page(client, f'/quiz/{chapter_id}', f'quiz/{chapter_id}')
        redirects.extend((f'/chapter/{chapter_id} /chapter/{chapter_id}/ 301', f'/quiz/{chapter_id} /quiz/{chapter_id}/ 301'))
        chapter_lessons = [lesson['id'] for lesson in chapter.get('lessons', [])]
        lesson_ids.extend(chapter_lessons)
        quiz = get_quiz(chapter_id)
        chapters[chapter_id] = {'lessonIds': chapter_lessons, 'quizTotal': len(quiz['questions'])}
        for lesson_id in chapter_lessons:
            write_page(client, f'/lesson/{lesson_id}', f'lesson/{lesson_id}')
            redirects.append(f'/lesson/{lesson_id} /lesson/{lesson_id}/ 301')
    for slug in RESOURCES:
        write_page(client, f'/resource/{slug}', f'resource/{slug}')
        redirects.append(f'/resource/{slug} /resource/{slug}/ 301')

    course_data = (
        '/* Generated by tools/build-static.py. */\n'
        f'const COURSE_DATA = Object.freeze({json.dumps({"lessonIds": lesson_ids, "chapters": chapters}, separators=(",", ":"))});\n'
    )
    (ROOT / 'app' / 'static' / 'js' / 'course-data.js').write_text(course_data, encoding='utf-8')
    shutil.copytree(ROOT / 'app' / 'static', DIST / 'static')
    (DIST / '_redirects').write_text('\n'.join(redirects) + '\n', encoding='utf-8')
    (DIST / '_headers').write_text('''/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Frame-Options: SAMEORIGIN
  Content-Security-Policy: default-src 'self'; base-uri 'self'; object-src 'none'; frame-ancestors 'self'; form-action 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self' 'wasm-unsafe-eval'; worker-src 'self'; connect-src 'self' https://kontor-tutor-worker.kwasikontor45-995.workers.dev; font-src 'self' data:
''', encoding='utf-8')
    print(f'Built {1 + len(CHAPTERS) * 2 + len(lesson_ids) + len(RESOURCES)} pages, {len(lesson_ids)} lessons, {len(redirects)} redirects into {DIST}')


if __name__ == '__main__':
    main()
